// Builds the database setup from supabase/migrations/*.sql:
//   supabase/setup.sql        every migration in order, in one file (for the CLI, psql, db:apply)
//   supabase/parts/NN-of-MM.sql   the same, in small parts to paste one at a time into the
//                                 dashboard's SQL editor (a paste can be cut off at about 4 KB).
//                                 Not committed (.gitignore): made here on demand.
// Run `npm run db:setup` after adding a migration; tests/sql.test.ts fails if setup.sql is stale.
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PART_LIMIT, partFiles } from './sql-split.mjs';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase');
const files = readdirSync(join(dir, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const header = `-- Endless Space: the whole database in one file. GENERATED by \`npm run db:setup\`
-- from supabase/migrations/*.sql: edit those, not this.
--
-- Safe on a fresh project. If pasting this into the Supabase SQL editor gets cut off,
-- run \`npm run db:setup\` and use the small files it writes in supabase/parts/ instead, one at a time, in order.

`;
const body = files.map((f) => `-- ===== ${f} =====\n\n${readFileSync(join(dir, 'migrations', f), 'utf8').trim()}\n`).join('\n');
writeFileSync(join(dir, 'setup.sql'), header + body);

// The same SQL in parts.
const all = files.map((f) => readFileSync(join(dir, 'migrations', f), 'utf8').trim()).join('\n\n');
const pieces = partFiles(all, PART_LIMIT);
rmSync(join(dir, 'parts'), { recursive: true, force: true });
mkdirSync(join(dir, 'parts'));
for (const { name, text } of pieces) writeFileSync(join(dir, 'parts', name), text);
console.log(`supabase/setup.sql: ${files.join(', ')}\nsupabase/parts/: ${pieces.length} parts of up to ${PART_LIMIT} bytes`);
