// Builds supabase/setup.sql: every migration in order, in one file to paste into
// the Supabase SQL editor. Run `npm run db:setup` after adding a migration;
// tests/sql.test.ts fails if the file is stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase');
const files = readdirSync(join(dir, 'migrations')).filter((f) => f.endsWith('.sql')).sort();
const header = `-- Endless Space: the whole database in one paste. GENERATED by \`npm run db:setup\`
-- from supabase/migrations/*.sql: edit those, not this.
--
-- Supabase dashboard > SQL editor > New query > paste this > Run.
-- Safe on a fresh project. (To change an existing one, run only the newer migrations.)

`;
const body = files.map((f) => `-- ===== ${f} =====\n\n${readFileSync(join(dir, 'migrations', f), 'utf8').trim()}\n`).join('\n');
writeFileSync(join(dir, 'setup.sql'), header + body);
console.log(`supabase/setup.sql: ${files.join(', ')}`);
